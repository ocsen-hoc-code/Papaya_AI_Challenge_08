#!/usr/bin/env python3
"""Manage task status in the tasks/ folder.

python3 tasks/tasks.py list [--status todo|pending|done]
python3 tasks/tasks.py next              # todo tasks whose dependencies are done
python3 tasks/tasks.py set T03 pending   # change status and regenerate BOARD.md
python3 tasks/tasks.py board             # regenerate BOARD.md
"""

import argparse
import re
import sys
from pathlib import Path

TASKS_DIR = Path(__file__).resolve().parent
STATUSES = ("todo", "pending", "done")
ICONS = {"todo": "⬜", "pending": "🟡", "done": "✅"}


def load_tasks():
    tasks = []
    for path in sorted(TASKS_DIR.glob("T*.md")):
        text = path.read_text(encoding="utf-8")
        m = re.match(r"---\n(.*?)\n---\n", text, re.S)
        if not m:
            continue
        meta = {}
        for line in m.group(1).splitlines():
            key, _, value = line.partition(":")
            meta[key.strip()] = value.strip()
        meta["depends_on"] = [d.strip() for d in meta.get("depends_on", "[]").strip("[]").split(",") if d.strip()]
        meta["path"] = path
        tasks.append(meta)
    return tasks


def write_board(tasks):
    done = sum(t["status"] == "done" for t in tasks)
    lines = [
        "# Task Board",
        "",
        "> Generated by `python3 tasks/tasks.py board`. Do not edit by hand.",
        "",
        f"**Progress:** {done}/{len(tasks)} done · "
        + " · ".join(f"{ICONS[s]} {s}: {sum(t['status'] == s for t in tasks)}" for s in STATUSES),
        "",
        "| ID | Phase | Task | Status | Estimate | Depends on |",
        "|---|---|---|---|---|---|",
    ]
    for t in tasks:
        deps = ", ".join(t["depends_on"]) or "—"
        lines.append(
            f"| [{t['id']}]({t['path'].name}) | {t['phase']} | {t['title']} "
            f"| {ICONS.get(t['status'], '?')} {t['status']} | {t['estimate']} | {deps} |"
        )
    (TASKS_DIR / "BOARD.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def ready(task, by_id):
    return task["status"] == "todo" and all(by_id[d]["status"] == "done" for d in task["depends_on"] if d in by_id)


def main():
    parser = argparse.ArgumentParser(description="Manage tasks: todo / pending / done")
    sub = parser.add_subparsers(dest="cmd", required=True)
    p_list = sub.add_parser("list")
    p_list.add_argument("--status", choices=STATUSES)
    sub.add_parser("next")
    p_set = sub.add_parser("set")
    p_set.add_argument("id")
    p_set.add_argument("status", choices=STATUSES)
    sub.add_parser("board")
    args = parser.parse_args()

    tasks = load_tasks()
    by_id = {t["id"]: t for t in tasks}

    if args.cmd == "list":
        for t in tasks:
            if args.status is None or t["status"] == args.status:
                print(f"{ICONS.get(t['status'], '?')} {t['id']}  [{t['status']:<7}] P{t['phase']}  {t['title']}")
    elif args.cmd == "next":
        for t in tasks:
            if ready(t, by_id):
                print(f"{t['id']}  P{t['phase']}  {t['title']}")
    elif args.cmd == "set":
        task = by_id.get(args.id.upper())
        if task is None:
            sys.exit(f"Task not found: {args.id}")
        text = task["path"].read_text(encoding="utf-8")
        task["path"].write_text(
            re.sub(r"^status: .*$", f"status: {args.status}", text, count=1, flags=re.M), encoding="utf-8"
        )
        task["status"] = args.status
        write_board(tasks)
        print(f"{task['id']} → {args.status}")
    elif args.cmd == "board":
        write_board(tasks)
        print("BOARD.md updated")


if __name__ == "__main__":
    main()
